/**
 * Deterministic Project Intelligence Index.
 * Five dimensions (0–100 each), weighted 25/20/25/15/15 into an overall
 * score, mapped to grades A (≥90) … F (<50).
 */
export const computeIntelligenceIndex = (input: IntelligenceInput): IntelligenceIndex => {
  const dimensions: IntelligenceDimension[] = [
    scorePlanning(input),
    scoreBudget(input),
    scoreSchedule(input),
    scoreQuality(input),
    scoreStaffing(input),
  ];

  const totalWeight = dimensions.reduce((s, d) => s + d.weight, 0);
  const overall = round(
    dimensions.reduce((s, d) => s + d.score * d.weight, 0) / Math.max(1, totalWeight)
  );

  return { overall, grade: gradeFromScore(overall), dimensions };
};

// ── AI feedback ──────────────────────────────────────────────────────────────

/** Strip markdown fences and extract the outermost JSON object from AI text. */
const extractJson = (text: string): unknown => {
  const cleaned = text.replace(/```(?:json)?/gi, '').trim();
  const start = cleaned.indexOf('{');
  const end = cleaned.lastIndexOf('}');
  if (start === -1 || end === -1 || end <= start) throw new Error('No JSON object in AI response');
  return JSON.parse(cleaned.slice(start, end + 1));
};

const coerceImpact = (value: unknown): IndexAction['impact'] => {
  const v = String(value ?? '').toLowerCase();
  if (v.includes('høj') || v.includes('hoj') || v === 'high') return 'høj';
  if (v.includes('lav') || v === 'low') return 'lav';
  return 'mellem';
};

/** Deterministic feedback built from the index drivers — no AI required. */
export const buildFallbackFeedback = (index: IntelligenceIndex): IndexFeedback => {
  const sorted = [...index.dimensions].sort((a, b) => a.score - b.score);
  const weakest = sorted.slice(0, 2);
  const strongest = sorted[sorted.length - 1];

  const summary =
    `Projektet scorer ${index.overall}/100 (karakter ${index.grade}). ` +
    `Stærkeste område er ${strongest.label.toLowerCase()} (${strongest.score}), ` +
    `mens ${weakest.map(d => d.label.toLowerCase()).join(' og ')} trækker ned ` +
    `(${weakest.map(d => d.score).join(' og ')}).`;

  const actionTitleByDim: Record<DimensionId, string> = {
    planning: 'Styrk planlægningen med beskrivelser, deadlines og rækkefølge',
    budget: 'Få styr på budgetramme og prisdata på indkøb',
    schedule: 'Håndtér forfaldne opgaver og genberegn tidsplanen',
    quality: 'Tilføj fotos, tjeklister og dokumentation på opgaverne',
    staffing: 'Fordel ansvar og arbejdsbyrde på flere teammedlemmer',
  };

  const topActions: IndexAction[] = weakest.map((dim, i) => ({
    title: actionTitleByDim[dim.id],
    why: dim.drivers[0] ?? `${dim.label} scorer kun ${dim.score}/100.`,
    impact: i === 0 ? 'høj' : 'mellem',
  }));

  const risks = index.dimensions
    .filter(d => d.score < 50)
    .map(d => `${d.label} er kritisk lav (${d.score}/100): ${d.drivers[0] ?? 'kræver handling'}`);

  return { summary, topActions, risks, source: 'fallback' };
};

/**
 * One AI call that turns the deterministic index into Danish feedback.
 * Falls back to `buildFallbackFeedback` on any error or malformed JSON.
 */
export const generateIndexFeedback = async (
  index: IntelligenceIndex,
  context: IndexFeedbackContext
): Promise<IndexFeedback> => {
  const { project, tasks, purchases } = context;
  const openTasks = tasks.filter(t => t.status !== 'Udført').length;

  const prompt = `Projekt: "${project.name}" (status: ${project.status}, fremdrift: ${project.progress}%).
Kunde: ${project.clientName || 'ukendt'}. Periode: ${project.startDate || '?'} – ${project.endDate || '?'}.
Opgaver: ${tasks.length} i alt, ${openTasks} åbne. Indkøbslinjer: ${purchases.length}.

Intelligensindeks (deterministisk beregnet):
Samlet: ${index.overall}/100 (karakter ${index.grade})
${index.dimensions
  .map(d => `- ${d.label}: ${d.score}/100 (vægt ${d.weight}%)\n  Drivere: ${d.drivers.join(' | ')}`)
  .join('\n')}

Returnér KUN gyldig JSON (ingen markdown, ingen forklaring) på dansk i dette format:
{"summary": "2-3 sætninger om projektets tilstand", "topActions": [{"title": "konkret handling", "why": "kort begrundelse", "impact": "høj|mellem|lav"}], "risks": ["konkret risiko", "..."]}
Maks 4 topActions og maks 4 risks. Vær konkret og handlingsorienteret som en erfaren dansk byggeleder.`;

  try {
    const text = await aiChat({
      prompt,
      system:
        'Du er en erfaren dansk byggeleder og projektchef. Du svarer altid udelukkende med gyldig JSON uden markdown-formatering.',
      feature: 'project-evaluation',
      temperature: 0.4,
    });

    const raw = extractJson(text) as {
      summary?: unknown;
      topActions?: unknown;
      risks?: unknown;
    };

    const summary = typeof raw.summary === 'string' && raw.summary.trim() ? raw.summary.trim() : null;
    const topActions: IndexAction[] = Array.isArray(raw.topActions)
      ? raw.topActions
          .filter((a): a is Record<string, unknown> => !!a && typeof a === 'object')
          .map(a => ({
            title: String(a.title ?? '').trim(),
            why: String(a.why ?? '').trim(),
            impact: coerceImpact(a.impact),
          }))
          .filter(a => a.title)
          .slice(0, 4)
      : [];
    const risks: string[] = Array.isArray(raw.risks)
      ? raw.risks.map(r => String(r ?? '').trim()).filter(Boolean).slice(0, 4)
      : [];

    if (!summary || topActions.length === 0) {
      // AI returned something unusable — degrade gracefully.
      return buildFallbackFeedback(index);
    }

    return { summary, topActions, risks, source: 'ai' };
  } catch {
    return buildFallbackFeedback(index);
  }
};
